# Parse CLI args
if [[ $# -eq 0 ]]; then
  main_menu
  exit 0
fi

case "$1" in
  -h|--help) usage; exit 0 ;;
  --list)
    get_all_skills
    ;;
  --list-groups)
    for f in "$GROUPS_DIR"/*.group; do
      [[ -f "$f" ]] || continue
      grep -q '^\[skills\]' "$f" || continue
      _name=$(basename "$f" .group)
      _desc=$(group_description "$f")
      _count=$(parse_group "$f" | wc -l | tr -d ' ')
      printf "%-25s (%s skills)  %s\n" "$_name" "$_count" "$_desc"
    done
    ;;
  --installed)
    _found=0
    for _type in agents skills rules workflows hooks mcp; do
      load_installed_type "$_type"
      if [[ ${#INSTALLED_ITEMS[@]} -gt 0 ]]; then
        echo "${_type}:"
        for s in "${INSTALLED_ITEMS[@]}"; do echo "  $s"; done
        _found=1
      fi
    done
    [[ $_found -eq 0 ]] && echo "Nothing installed"
    ;;
  --install)
    # Install the default group
    _grp_file="$GROUPS_DIR/default.group"
    [[ -f "$_grp_file" ]] || { err "Default group not found"; exit 1; }
    info "Installing default group..."
    for _type in agents skills rules workflows hooks mcp; do
      _items=()
      while IFS= read -r s; do
        [[ -n "$s" ]] && _items+=("$s")
      done < <(parse_group_section "$_grp_file" "$_type")
      if [[ ${#_items[@]} -gt 0 ]]; then
        install_type "$_type" "${_items[@]}"
      fi
    done
    ;;
  --install-agent|--install-skill|--install-rule|--install-workflow|--install-hook|--install-mcp)
    _type="${1#--install-}"
    # Normalize singular to plural directory name
    case "$_type" in
      agent) _type="agents" ;;
      skill) _type="skills" ;;
      rule)  _type="rules" ;;
      workflow) _type="workflows" ;;
      hook)  _type="hooks" ;;
      # mcp stays as mcp
    esac
    shift
    [[ $# -eq 0 ]] && { err "Provide names (comma-separated)"; exit 1; }
    IFS=',' read -ra _items <<< "$1"
    install_type "$_type" "${_items[@]}"
    ;;
  --install-group)
    shift
    [[ $# -eq 0 ]] && { err "Provide group name"; exit 1; }
    _grp_file="$GROUPS_DIR/$1.group"
    [[ -f "$_grp_file" ]] || { err "Group not found: $1"; exit 1; }
    # Install all types from the group
    for _type in agents skills rules workflows hooks mcp; do
      _items=()
      while IFS= read -r s; do
        [[ -n "$s" ]] && _items+=("$s")
      done < <(parse_group_section "$_grp_file" "$_type")
      if [[ ${#_items[@]} -gt 0 ]]; then
        install_type "$_type" "${_items[@]}"
      fi
    done
    ;;
  --install-group-*)
    _type="${1#--install-group-}"
    shift
    [[ $# -eq 0 ]] && { err "Provide group name"; exit 1; }
    # Validate type
    case "$_type" in
      agents|skills|rules|workflows|hooks|mcp) ;;
      *) err "Unknown type: $_type (valid: agents, skills, rules, workflows, hooks, mcp)"; exit 1 ;;
    esac
    _grp_file="$GROUPS_DIR/$1.group"
    [[ -f "$_grp_file" ]] || { err "Group not found: $1"; exit 1; }
    _items=()
    while IFS= read -r s; do
      [[ -n "$s" ]] && _items+=("$s")
    done < <(parse_group_section "$_grp_file" "$_type")
    if [[ ${#_items[@]} -eq 0 ]]; then
      warn "No $_type found in group: $1"
      exit 0
    fi
    install_type "$_type" "${_items[@]}"
    ;;
  --install-all)
    # Install everything across all types
    for _type in agents skills rules workflows hooks mcp; do
      _all=()
      while IFS= read -r s; do
        [[ -n "$s" ]] && _all+=("$s")
      done < <(get_all_type "$_type")
      if [[ ${#_all[@]} -gt 0 ]]; then
        install_type "$_type" "${_all[@]}"
      fi
    done
    ;;
  --install-all-*)
    _type="${1#--install-all-}"
    case "$_type" in
      agents|skills|rules|workflows|hooks|mcp) ;;
      *) err "Unknown type: $_type (valid: agents, skills, rules, workflows, hooks, mcp)"; exit 1 ;;
    esac
    _all=()
    while IFS= read -r s; do
      [[ -n "$s" ]] && _all+=("$s")
    done < <(get_all_type "$_type")
    if [[ ${#_all[@]} -eq 0 ]]; then
      warn "No $_type found"
      exit 0
    fi
    install_type "$_type" "${_all[@]}"
    ;;
  --uninstall-agent|--uninstall-skill|--uninstall-rule|--uninstall-workflow|--uninstall-hook|--uninstall-mcp)
    _type="${1#--uninstall-}"
    case "$_type" in
      agent) _type="agents" ;;
      skill) _type="skills" ;;
      rule)  _type="rules" ;;
      workflow) _type="workflows" ;;
      hook)  _type="hooks" ;;
    esac
    shift
    [[ $# -eq 0 ]] && { err "Provide names (comma-separated)"; exit 1; }
    load_installed_type "$_type"
    IFS=',' read -ra to_remove <<< "$1"
    for r in "${to_remove[@]}"; do
      r="$(echo "$r" | tr -d ' ')"
      INSTALLED_ITEMS=($(toggle_selection "$r" "${INSTALLED_ITEMS[@]+"${INSTALLED_ITEMS[@]}"}"))
      ok "Uninstalled ${_type%s}: $r"
    done
    save_installed_type "$_type"
    ;;
  --list-templates)
    TEMPLATES_DIR="$SCRIPT_DIR/templates"
    for f in "$TEMPLATES_DIR"/*.template; do
      [[ -f "$f" ]] || continue
      _name=$(basename "$f" .template)
      _desc=$(head -1 "$f" | sed 's/^# //')
      printf "%-25s %s\n" "$_name" "$_desc"
    done
    ;;
  --template)
    shift
    [[ $# -eq 0 ]] && { err "Provide template name"; exit 1; }
    _tpl_name="$1"
    _tpl_file="$SCRIPT_DIR/templates/${_tpl_name}.template"
    [[ -f "$_tpl_file" ]] || { err "Template not found: $_tpl_name"; exit 1; }
    info "Installing template: $_tpl_name"
    _TPL_SECTION=""
    while IFS= read -r line; do
      line="${line%%#*}"
      line="$(echo "$line" | sed 's/^[[:space:]]*//;s/[[:space:]]*$//')"
      [[ -z "$line" ]] && continue
      if [[ "$line" == "["*"]" ]]; then
        _TPL_SECTION="${line:1:${#line}-2}"
        continue
      fi
      if [[ -n "$_TPL_SECTION" ]]; then
        case "$_TPL_SECTION" in
          groups)
            _grp_file="$GROUPS_DIR/${line}.group"
            [[ -f "$_grp_file" ]] || { warn "Group not found in template: $line"; continue; }
            for _type in agents skills rules workflows hooks mcp; do
              _items=()
              while IFS= read -r s; do
                [[ -n "$s" ]] && _items+=("$s")
              done < <(parse_group_section "$_grp_file" "$_type")
              if [[ ${#_items[@]} -gt 0 ]]; then
                install_type "$_type" "${_items[@]}"
              fi
            done
            ;;
          agents|skills|rules|workflows|hooks|mcp)
            install_type "$_TPL_SECTION" "$line"
            ;;
        esac
      fi
    done < "$_tpl_file"
    # Save template as project config if not --global
    _global=false
    for _a in "$@"; do [[ "$_a" == "--global" || "$_a" == "-g" ]] && _global=true; done
    if [[ "$_global" == false ]]; then
      _project_root="$(git rev-parse --show-toplevel 2>/dev/null || pwd)"
      echo "$_tpl_name" > "$_project_root/.ai-management"
      ok "Saved template → $_project_root/.ai-management"
    fi
    info "Run ${CYAN}sync.sh --template $_tpl_name${NC} to deploy"
    ;;
  *)
    err "Unknown option: $1"
    usage
    exit 1
    ;;
esac
