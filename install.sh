# Migrate legacy installed-skills.conf if present
_migrate_legacy() {
  local legacy="$AI_MGMT_HOME/installed-skills.conf"
  if [[ -f "$legacy" && ! -f "$INSTALLED_DIR/skills.conf" ]]; then
    mkdir -p "$INSTALLED_DIR"
    cp "$legacy" "$INSTALLED_DIR/skills.conf"
    rm -f "$legacy"
  fi
}
