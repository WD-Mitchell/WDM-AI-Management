# ── Discover all items for any content type ───────────────────
get_all_type() {
  local type="$1"
  local type_dir="$SCRIPT_DIR/$type"
  local -a items=()

  [[ -d "$type_dir" ]] || { return 0; }

  # Skills/hooks use subdirectories; agents/rules/workflows/mcp use .md files
  case "$type" in
    skills)
      for d in "$type_dir"/*/; do
        [[ -d "$d" ]] || continue
        local name
        name=$(basename "$d")
        # Skip build output dirs
        local skip=0
        for h in $HARNESS_DIRS; do [[ "$name" == "$h" ]] && skip=1; done
        [[ $skip -eq 1 ]] && continue
        [[ -f "$d/SKILL.md" ]] || continue
        items+=("$name")
      done
      ;;
    hooks)
      for entry in "$type_dir"/*; do
        [[ -e "$entry" ]] || continue
        local name
        name=$(basename "$entry")
        local skip=0
        for h in $HARNESS_DIRS; do [[ "$name" == "$h" ]] && skip=1; done
        [[ $skip -eq 1 ]] && continue
        items+=("$name")
      done
      ;;
    *)
      # agents, rules, workflows, mcp — flat .md files
      for f in "$type_dir"/*.md; do
        [[ -f "$f" ]] || continue
        local name
        name=$(basename "$f" .md)
        items+=("$name")
      done
      ;;
  esac

  printf '%s\n' "${items[@]+"${items[@]}"}" | sort
}

# ── Parse a group file for its [skills] section ───────────────
parse_group() {
  parse_group_section "$1" "skills"
}

# ── Parse any section from a group file ───────────────────────
parse_group_section() {
  local group_file="$1"
  local section="$2"
  local -a items=()
  local in_section=0

  while IFS= read -r line; do
    line="${line%%#*}"
    line="$(echo "$line" | sed 's/^[[:space:]]*//;s/[[:space:]]*$//')"
    [[ -z "$line" ]] && continue

    # Section header
    if [[ "$line" == "["*"]" ]]; then
      if [[ "$line" == "[$section]" ]]; then
        in_section=1
      else
        in_section=0
      fi
      continue
    fi

    if [[ $in_section -eq 1 ]]; then
      # Wildcard means all items in that type's directory
      if [[ "$line" == "*" ]]; then
        local type_dir="$SCRIPT_DIR/$section"
        if [[ -d "$type_dir" ]]; then
          for d in "$type_dir"/*/; do
            [[ -d "$d" ]] || continue
            local basename_d
            basename_d=$(basename "$d")
            [[ "$basename_d" == "__pycache__" ]] && continue
            items+=("$basename_d")
          done
        fi
      else
        items+=("$line")
      fi
    fi
  done < "$group_file"

  printf '%s\n' "${items[@]+"${items[@]}"}" | sort -u
}

# ── Get group description (first comment line) ────────────────
group_description() {
  head -1 "$1" | sed 's/^# //'
}

# ── Get skill description from SKILL.md frontmatter ───────────
skill_description() {
  local skill_dir="$SKILLS_DIR/$1"
  [[ -f "$skill_dir/SKILL.md" ]] || return
  # Extract description from YAML frontmatter
  sed -n '/^---$/,/^---$/p' "$skill_dir/SKILL.md" | grep -m1 "^description:" | sed "s/^description:[[:space:]]*//;s/^['\"]//;s/['\"]$//" | head -c 70
}

# ── Toggle selection in array ─────────────────────────────────
toggle_selection() {
  local item="$1"
  shift
  local -a arr=("$@")
  local found=false
  local -a new_arr=()

  for s in "${arr[@]+"${arr[@]}"}"; do
    if [[ "$s" == "$item" ]]; then
      found=true
    else
      new_arr+=("$s")
    fi
  done

  if ! $found; then
    new_arr+=("$item")
  fi

  printf '%s\n' "${new_arr[@]+"${new_arr[@]}"}"
}

is_in_array() {
  local item="$1"
  shift
  for s in "$@"; do
    [[ "$s" == "$item" ]] && return 0
  done
  return 1
}

# ═══════════════════════════════════════════════════════════════
